"""Build registry.json and registry.md from results/models/*.json (T421). Point status per the pre-registered rule:
kept = >= 3 of the 6 cpu seeds reach acc >= .90 (anchor (16,10) always kept); screened = cpu seeds 0 and 1 both < .80
(seeds >= 2 not trained); dropped = all 6 cpu seeds done and < 3 reach .90; pending otherwise."""
import glob
import json
import os
import statistics

HERE = os.path.dirname(os.path.abspath(__file__))
KEYS = ("tag", "H", "T", "seed", "stream", "acc", "se", "pth", "npz", "sha256_npz_weights")
models = sorted((json.load(open(p)) for p in glob.glob(os.path.join(HERE, "results/models/*.json"))),
                key=lambda r: (r["T"], r["H"], r["stream"], r["seed"]))
points = []
for T in (10, 15, 20):
    for H in (16, 24, 32, 48, 64):
        cpu = [r["acc"] for r in models if (r["H"], r["T"], r["stream"]) == (H, T, "cpu")]
        zoo = [r["acc"] for r in models if (r["H"], r["T"], r["stream"]) == (H, T, "zoo")]
        good = sum(a >= 0.90 for a in cpu)
        accs01 = [r["acc"] for r in models if (r["H"], r["T"], r["stream"]) == (H, T, "cpu") and r["seed"] < 2]
        if (H, T) == (16, 10) or good >= 3:
            status = "kept"
        elif len(accs01) == 2 and max(accs01) < 0.80:
            status = "screened"
        elif len(cpu) >= 6:
            status = "dropped"
        else:
            status = "pending"
        points.append({"H": H, "T": T, "status": status, "n_cpu": len(cpu), "n_cpu_ge_.90": good,
                       "cpu_min": min(cpu, default=None), "cpu_median": statistics.median(cpu) if cpu else None,
                       "cpu_max": max(cpu, default=None), "n_zoo": len(zoo), "zoo_max": max(zoo, default=None)})
json.dump({"models": [{k: r[k] for k in KEYS} | {"source": r["provenance"]["source"]} for r in models],
           "points": points}, open(os.path.join(HERE, "registry.json"), "w"), indent=1)
f = lambda a: "-" if a is None else f"{a:.4f}"
with open(os.path.join(HERE, "registry.md"), "w") as o:
    o.write("# T421 grid registry (generated by build_registry.py; do not edit)\n\n## Points\n\n"
            "| H | T | status | cpu seeds | >= .90 | min | median | max | zoo seeds | zoo best |\n|---|---|---|---|---|---|---|---|---|---|\n")
    for p in points:
        o.write(f"| {p['H']} | {p['T']} | {p['status']} | {p['n_cpu']} | {p['n_cpu_ge_.90']} | {f(p['cpu_min'])} | "
                f"{f(p['cpu_median'])} | {f(p['cpu_max'])} | {p['n_zoo']} | {f(p['zoo_max'])} |\n")
    o.write("\n## Models (accuracy: 1e7 MC, evaluate.py)\n\n| tag | H | T | stream | seed | acc | se | weights |\n|---|---|---|---|---|---|---|---|\n")
    for r in models:
        o.write(f"| {r['tag']} | {r['H']} | {r['T']} | {r['stream']} | {r['seed']} | {r['acc']:.5f} | {r['se']:.1e} | "
                f"[pth]({r['pth']}) [npz]({r['npz']}) |\n")
print(*(f"{p['H']},{p['T']} {p['status']} n={p['n_cpu']} med={f(p['cpu_median'])}" for p in points), sep="\n")
