"""T427 scoring (pre-registered in README): per (model, t) label rated / unrated / beyond test, per grid point the rated
fraction and 'holds' (>= 2/3), per model the rated depth, trust flag det vs sampled, F vs both bars (informative iff
p C >= 1). Reads results/est_*.json and results/mc_*.json for models that have both. -> results/score.md, score.json"""
import glob
import json
import os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(HERE, "results")
HMIN = 50
rows = []; models = []
for pe in sorted(glob.glob(os.path.join(R, "est_m_*.json"))):
    e = json.load(open(pe)); pm = os.path.join(R, f"mc_{e['tag']}.json")
    if not os.path.exists(pm):
        continue
    mc = json.load(open(pm)); assert mc["sha256"] == e["sha256"]
    if len(mc["pts"]) < len(e["pts"]):
        continue
    stream = e["tag"].split("_")[-1].rstrip("0123456789"); depth = 0; broken = False
    for j, (k, p) in enumerate(sorted(e["pts"].items(), key=lambda kv: kv[1]["t"])):
        c = mc["pts"][k]; est_r = p["est"] / p["P_cond"]; row = dict(tag=e["tag"], H=e["H"], T=e["T"], stream=stream, j=j, t=p["t"],
                                                                  P=p["P_cond"], r_est=est_r, flag_det=p["flag_det"], hits=c["hits"], n=c["n"])
        if c["hits"] >= HMIN:
            q = c["rate"]; ratio = est_r / q; pj = q * p["P_cond"]; C = e["C"]
            F = (p["est"] - pj) ** 2 * max(C, 1000) / (pj * (1 - pj))
            row.update(r_mc=q, r_se=c["rate_se"], ratio=ratio, label="rated" if 0.5 <= ratio <= 2 else "unrated",
                       flag_mc=c["tie_share"], F=F, pC=pj * C, F_inf=bool(pj * C >= 1))
            if row["label"] == "rated" and not broken:
                depth = j + 1
            elif row["label"] == "unrated":
                broken = True
        else:
            row.update(label="beyond test", r_mc=(c["rate"] if c["hits"] else 0.0))
        rows.append(row)
    models.append(dict(tag=e["tag"], H=e["H"], T=e["T"], stream=stream, acc=e["acc"], C=e["C"], sec=e["sec"], itmax=e["itmax"],
                       depth=depth, n_chk=sum(r["label"] != "beyond test" for r in rows if r["tag"] == e["tag"]),
                       n_rated=sum(r["label"] == "rated" for r in rows if r["tag"] == e["tag"])))

L = ["# T427 scores (generated by score.py)", "", "## Per grid point (primary = cpu stream)", "",
     "| H | T | stream | models | checkable | rated | rated fraction | holds (>= 2/3) | rated depth per model (of 7) | C (M FPE) median |",
     "|---|---|---|---|---|---|---|---|---|---|"]
pts = defaultdict(list)
for m in models:
    pts[(m["T"], m["H"], m["stream"])].append(m)
summary = []
for (T, H, s), ms in sorted(pts.items(), key=lambda kv: (kv[0][2] != "cpu", kv[0][0], kv[0][1])):
    chk = sum(m["n_chk"] for m in ms); rt = sum(m["n_rated"] for m in ms); fr = rt / chk if chk else float("nan")
    summary.append(dict(H=H, T=T, stream=s, models=len(ms), checkable=chk, rated=rt, frac=fr, holds=bool(chk and fr >= 2 / 3)))
    L.append(f"| {H} | {T} | {s} | {len(ms)} | {chk} | {rt} | {fr:.2f} | {'yes' if chk and fr >= 2 / 3 else 'no'} | "
             f"{', '.join(str(m['depth']) for m in ms)} | {np.median([m['C'] for m in ms]) / 1e6:.2f} |")
L += ["", "## Per (model, t)", "", "| model | acc | j | t | P(cond) | r est | r check (s.e.) | hits | est / check | label | flag det | flag MC | F | pC | F informative |",
      "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
acc = {m["tag"]: m["acc"] for m in models}
for r in rows:
    if r["label"] == "beyond test":
        L.append(f"| {r['tag']} | {acc[r['tag']]:.4f} | {r['j']} | {r['t']:.3f} | {r['P']:.3g} | {r['r_est']:.3g} | {r['r_mc']:.2g} (< {HMIN} hits) | {r['hits']} | - | beyond test | "
                 f"{r['flag_det']:.2f} | - | - | - | - |")
    else:
        L.append(f"| {r['tag']} | {acc[r['tag']]:.4f} | {r['j']} | {r['t']:.3f} | {r['P']:.3g} | {r['r_est']:.3g} | {r['r_mc']:.3g} ({r['r_se']:.1g}) | {r['hits']} | {r['ratio']:.2f} | "
                 f"{r['label']} | {r['flag_det']:.2f} | {r['flag_mc']:.2f} | {r['F']:.3g} | {r['pC']:.3g} | {'yes' if r['F_inf'] else 'no'} |")
ck = [r for r in rows if r["label"] != "beyond test"]
if len(ck) > 2:
    fd = np.array([r["flag_det"] for r in ck]); fs = np.array([r["flag_mc"] for r in ck]); ok = np.array([r["label"] == "rated" for r in ck])
    lo = fd < 0.5
    L += ["", "## Trust flag (checkable points)", "",
          f"corr(det, sampled) {np.corrcoef(fd, fs)[0, 1]:.2f}; >= 50% call agrees {int(((fd >= .5) == (fs >= .5)).sum())}/{len(fd)}; "
          f"mean |det - sampled| {np.abs(fd - fs).mean():.2f}; rated among det < .5: {ok[lo].sum()}/{lo.sum()}; among det >= .5: {ok[~lo].sum()}/{(~lo).sum()}"]
    inf = [r for r in ck if r["F_inf"]]
    L += ["", "## F (informative points only, p C >= 1)", "",
          f"{len(inf)} informative of {len(ck)} checkable; strict F <= 1: {sum(r['F'] <= 1 for r in inf)}; lenient F <= 10: {sum(r['F'] <= 10 for r in inf)}"]
L += ["", "## Models", "", "| model | acc | C (M FPE) | sec | walk max cells | checkable | rated | depth |", "|---|---|---|---|---|---|---|---|"]
L += [f"| {m['tag']} | {m['acc']:.4f} | {m['C'] / 1e6:.2f} | {m['sec']:.0f} | {m['itmax']} | {m['n_chk']} | {m['n_rated']} | {m['depth']} |" for m in models]
open(os.path.join(R, "score.md"), "w").write("\n".join(L) + "\n")
json.dump(dict(points=summary, models=models, rows=rows), open(os.path.join(R, "score.json"), "w"), indent=1)
print("\n".join(L[:6 + len(summary)]))
