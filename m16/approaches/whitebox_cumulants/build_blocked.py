"""Generate a reviewable, licensed row-blocked derivative of pinned V25."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
manifest = json.loads((HERE/'sources.json').read_text())
original = Path(manifest['v25']['local_path']).read_text()
assert hashlib.sha256(original.encode()).hexdigest() == manifest['v25']['sha256']
start = original.index('    def _dslices(')
end = original.index('\n\nif __name__', start)
method = original[start:end]
rows = method.replace('def _dslices(', 'def _dslices_rows(', 1).replace('U2=None):', 'U2=None, row_start=0, row_stop=None):', 1)
docstart = rows.index('"""')
docend = rows.index('"""', docstart+3)+3
rows = rows[:docend]+'''
        row_stop = n if row_stop is None else row_stop
        nr = row_stop - row_start
        rs = slice(row_start, row_stop)
        A_full, P_full, Z_full = A_st, P_st, Z_st
        Zf_full = Zf_st
        A_st, P_st, Z_st = A_st[:, rs, :], P_st[:, rs, :], Z_st[:, rs, :]
        Zf_st = None if Zf_st is None else Zf_st[:, rs, :]
'''+rows[docend:]
# Only scratch buffers are sliced down to the active row count.
import re
rows = re.sub(r'(bufs\["\w+"\])\[:k\]', r'\1[:k, :nr]', rows)
replacements = {
    'GYR, F2)': 'GYR, Zf_full[:, :, rfb:])',
    'GXR, F1)': 'GXR, Zf_full[:, :, :rfb])',
    '(k, n, 1))': '(k, nr, 1))',
    'LA[ka:], A_st[ka:]': 'LA[ka:], A_full[ka:]',
    'LP[ka:], P_st[ka:]': 'LP[ka:], P_full[ka:]',
    '"kij,kcj->ic", LA, A_st': '"kij,kcj->ic", LA, A_full',
    '"kij,kcj->ic", LP, P_st': '"kij,kcj->ic", LP, P_full',
    '"ki,kc->ic", R, Yk': '"ki,kc->ic", R, Z_full[:, :, rres + 1]',
    '"kiq,kcq->ic", PPL, Z_st': '"kiq,kcq->ic", PPL, Z_full',
    'return D3, _zero_diag(D21)': 'return D3, D21',
}
for old,new in replacements.items():
    assert old in rows, old
    rows = rows.replace(old,new)
signature = method[:method.index('        """')]
wrapper = signature+'''        # Partition a free output index, never a source/reduction index.
        D3_out = fnp.empty(n, dtype=fnp.float32)
        D21_out = fnp.empty((n, n), dtype=fnp.float32) if need_d21 else None
        for lo in range(0, n, 128):
            hi = min(lo + 128, n)
            d3, d21 = self._dslices_rows(
                A_st, P_st, Z_st, L_st, w2b_list, s_list, e_list,
                c1_list, c2_list, y_list, n, bufs, rres, rfb,
                Zf_st, R1T_st, R2T_st, need_d21=need_d21,
                ka=ka, FAo=FAo, FPo=FPo, Qc=Qc,
                kb=kb, FA2=FA2, FP2=FP2, U2=U2,
                row_start=lo, row_stop=hi)
            fnp.copyto(D3_out[lo:hi], d3)
            if need_d21:
                fnp.copyto(D21_out[lo:hi], d21)
        return D3_out, _zero_diag(D21_out) if need_d21 else None

'''
source = original[:start]+wrapper+rows+original[end:]
old = 'bufs = {nm: fnp.empty((L - 1, n, n), dtype=f32)'
assert source.count(old)==1
source = source.replace(old, 'bufs = {nm: fnp.empty((L - 1, min(128, n), n), dtype=f32)')
source = source.replace('abbuf = fnp.empty((t2max, n, n), dtype=f32)', 'abbuf = fnp.empty((t2max, min(128, n), n), dtype=f32)')
start = source.index('            if not trim:\n                ab2 = prog["AB2"]')
end = source.index('            B1stack =',start)
source = source[:start]+'''            if not trim:
                ab2 = prog["AB2"]
                WL2 = fpm["SL2"] @ WT
                WR2 = fpm["SR2"] @ WT
                PK2 = fnp.empty((3, n, n), dtype=f32)
                for lo in range(0, n, 128):
                    hi = min(lo + 128, n)
                    nr = hi - lo
                    for t_, (a_, b_) in enumerate(ab2):
                        if a_ in ("ones2", "ones1"):
                            fnp.copyto(abbuf[t_, :nr], b2[b_][lo:hi])
                        elif b_ in ("ones2", "ones1"):
                            fnp.copyto(abbuf[t_, :nr], b2[a_][lo:hi])
                        else:
                            fnp.multiply(b2[a_][lo:hi], b2[b_][lo:hi], out=abbuf[t_, :nr])
                    part = fnp.einsum("tij,ti,tj,tg->gij", abbuf[:len(ab2), :nr],
                                      WL2[:, lo:hi], WR2, fpm["IND2"])
                    fnp.copyto(PK2[:, lo:hi], part)
'''+source[end:]
source = '# Derived from 504aldo V25 (MIT); see LICENSE.\n# T474 changes: row-block scratch and contractions only; generated by build_blocked.py.\n'+source
(HERE/'estimator_blocked.py').write_text(source)
# Keep the copyright/license with the redistributed derivative.
license_path = Path('/tmp/whitebox-review-k3/LICENSE')
(HERE/'LICENSE').write_text(license_path.read_text())
manifest['blocked'] = dict(manifest['v25'], local_path=str(HERE/'estimator_blocked.py'),
                          sha256=hashlib.sha256(source.encode()).hexdigest(),
                          derived=True, changes='128-row source-slice and nonlinear blocking')
(HERE/'sources.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('blocked SHA256',manifest['blocked']['sha256'])
