"""T195 pooled tables (markdown) from out/*.npz: per T, splits and exact class-changing mass (absdE) by driver rank,
step, step x rank, newest-input driver, cell-mass bucket, neuron concentration vs clock score.
usage: python report.py > report.md"""
import glob, json, os
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); THR = 1e-13


def ranks(perm):
    rk = np.empty_like(perm); rk[np.arange(len(perm))[:, None], perm] = np.arange(1, perm.shape[1] + 1)[None]; return rk


def spearman(a, b):
    ra, rb = np.argsort(np.argsort(a)), np.argsort(np.argsort(b)); return float(np.corrcoef(ra, rb)[0, 1])


print("# T195 pooled report (generated by report.py)\n")
for T in (3, 4, 5):
    fs = sorted(glob.glob(os.path.join(HERE, "out", f"H8_T{T}_s*.npz")))
    if not fs:
        continue
    R = [dict(np.load(f)) for f in fs]
    for r, f in zip(R, fs):
        rk = ranks(r["perm"].astype(int)); n = len(r["t"])
        r["drank"] = rk[np.arange(n), np.argmax(r["con"], 1)]; r["newest"] = np.argmax(r["con"], 1) == r["t"]
        r["seed"] = int(f[-5]); r["rk"] = rk
    cat = lambda key: np.concatenate([r[key] for r in R])
    t, dr, ab, mm, mc, nw = cat("t").astype(int), cat("drank"), cat("absdE"), cat("m_min"), cat("m_cell"), cat("newest")
    se = cat("s_err"); cls = ab > THR; N = len(t); A = ab.sum()
    print(f"## T = {T} ({len(R)} seed(s): {[r['seed'] for r in R]}), {N} resolved splits, sum absdE {A:.4g}\n")
    print("| driver rank | splits | share | exact class-changing share of splits | absdE share | minority-mass share | sampled err-change share |")
    print("|---|---|---|---|---|---|---|")
    for q in range(1, T + 1):
        m = dr == q
        print(f"| {q} | {m.sum()} | {m.mean():.3f} | {cls[m].mean() if m.any() else 0:.2f} | {ab[m].sum() / A:.3f} | {mm[m].sum() / mm.sum():.3f} | {(se[m] == 1).mean() if m.any() else 0:.2f} |")
    base = np.mean([(r["rk"][j, :int(r["t"][j]) + 1] >= 4).mean() for r in R for j in range(len(r["t"]))])
    per = [r["absdE"][r["drank"] >= 4].sum() / r["absdE"].sum() for r in R]
    print(f"\nrank >= 4: {np.mean(dr >= 4):.3f} of splits (uniform-over-available-inputs baseline {base:.3f}); "
          f"{ab[dr >= 4].sum() / A:.3f} of absdE pooled, per seed {np.round(per, 3).tolist()}\n")
    print("| step t | splits | share | absdE share | median cell mass | rank>=4 share of splits | rank>=4 share of absdE (within step) | newest-driver share of splits / absdE (within step) |")
    print("|---|---|---|---|---|---|---|---|")
    for s in np.unique(t):
        m = t == s
        print(f"| {s} | {m.sum()} | {m.mean():.3f} | {ab[m].sum() / A:.3f} | {np.median(mc[m]):.2g} | {np.mean(dr[m] >= 4):.3f} | {ab[m & (dr >= 4)].sum() / ab[m].sum():.3f} | {nw[m].mean():.3f} / {ab[m & nw].sum() / ab[m].sum():.3f} |")
    print(f"\nnewest input (index t) is the driver: {nw.mean():.3f} of splits, {ab[nw].sum() / A:.3f} of absdE\n")
    edges = [0, 1e-8, 1e-6, 1e-4, 1e-2, 1.01]
    print("cell-mass bucket [lo, hi): splits share / absdE share: " + "; ".join(
        f"[{edges[i]:g},{edges[i + 1]:g}) {((mc >= edges[i]) & (mc < edges[i + 1])).mean():.3f} / {ab[(mc >= edges[i]) & (mc < edges[i + 1])].sum() / A:.3f}"
        for i in range(5)))
    print(f"\nsplits with own absdE < 1e-6: {np.mean(ab < 1e-6):.3f} (their rank>=4 share {np.mean(dr[ab < 1e-6] >= 4):.3f}); "
          f"< 1e-8: {np.mean(ab < 1e-8):.3f}\n")
    rows = []
    for r in R:
        k = r["k"].astype(int); ns = np.bincount(k, minlength=8) / len(k); asd = np.bincount(k, weights=r["absdE"], minlength=8) / r["absdE"].sum()
        cf = os.path.join(HERE, "clocks", f"H8_T{T}_s{r['seed']}.json")
        ck = np.array([json.load(open(cf))[str(j)]["clock"] for j in range(8)]) if os.path.exists(cf) else None
        rows.append(f"seed {r['seed']}: max neuron split share {ns.max():.2f}, max neuron absdE share {asd.max():.2f}"
                    + (f", Spearman(clock score, absdE share) {spearman(ck, asd):+.2f}" if ck is not None else ""))
    print("neurons: " + "; ".join(rows) + "\n")
